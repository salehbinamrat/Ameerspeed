'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const crypto=require('node:crypto');
const source=fs.readFileSync('js/main.min.js','utf8');
for(const file of ['login.html','flogin.html']){
  const content=fs.readFileSync(file,'utf8');
  assert(content.startsWith('$(if var == "chapdata")'),file+' must serve challenge from login servlet');
  assert(content.includes('AMEER_CHAP_V1'),file+' missing versioned probe');
  assert(content.includes('$(chap-id)')&&content.includes('$(chap-challenge)'),file+' must expose RouterOS challenge tokens');
}
assert(source.includes('function decodeRouterChapByteString('),'byte decoder missing');
assert(source.includes('function parseRouterChapProbe('),'validated probe parser missing');
assert(source.includes('function loginWithRouterChap('),'CHAP-aware login missing');
assert(source.includes('loginWithRouterChap(fields, epoch)'),'the user login must use the CHAP handshake');
const cookies=fs.readFileSync('js/hotCookie.min.js','utf8');
assert(cookies.includes('loginWithRouterChap(fields, epoch)'),'auto-login must also use CHAP handshake');
assert(!cookies.includes("getRequest('/login?var=callBack', fields, 'login')"),'auto-login must not bypass CHAP verification');
assert(source.includes("getRequest('/login?var=callBack', fields, 'login')"),'retains existing RouterOS POST destination');
const start=source.indexOf('function decodeRouterChapByteString(');
const end=source.indexOf('function getChosenSpeed()',start);
assert(start>=0&&end>start);
const ctx={Date,Math,Array,String,RegExp,Number,parseInt,hotChapMd5:require('../js/md5.js')};
vm.createContext(ctx);
vm.runInContext(source.slice(start,end),ctx);
const raw='AMEER_CHAP_V1\nCHAP\n\\371\n\\357\\015\\330\\013\n';
const out=ctx.parseRouterChapProbe(raw);
assert.equal(out.mode,'chap');
assert.equal(out.id.charCodeAt(0),0xf9);
assert.equal(out.challenge.length,4);
const expected=crypto.createHash('md5').update(Buffer.from([0xf9,0xef,0x0d,0xd8,0x0b])).digest('hex');
assert.equal(ctx.hotChapMd5(out.id+out.challenge),expected);
assert.equal(ctx.parseRouterChapProbe('AMEER_CHAP_V1\nPAP\n').mode,'pap');
assert.equal(ctx.parseRouterChapProbe('<html>old gateway</html>'),null);
assert.equal(ctx.parseRouterChapProbe('AMEER_CHAP_V1\nCHAP\n$(chap-id)\n$(chap-challenge)'),null);
assert.equal(ctx.parseRouterChapProbe('AMEER_CHAP_V1\nCHAP\n\\377\n\\456'),null);
assert.equal(ctx.parseRouterChapProbe('AMEER_CHAP_V1\nCHAP\n\\377\n'),null);
console.log('PASS CHAP probe: RouterOS octal bytes, PAP fallback, unexpanded/malformed templates, MD5 validation');
