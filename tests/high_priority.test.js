assert(/var == ""/.test(login) && /<form[^>]*id="basicHotspotLogin"/.test(login), 'A04 no-JS primary login page must provide a usable fallback');
assert(/function showVerifiedSession\(/.test(src), 'A02/B07 only show success once status confirms username');
